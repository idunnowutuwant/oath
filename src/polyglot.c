void oath_emit_typescript_wrapper(FILE* out, const OirModule* mod, const char* module_name) {
    fprintf(out, "// Auto-generated TypeScript/WASM Bridge by OATH v3\n");
    fprintf(out, "export interface %sExports {\n", module_name);
    for (size_t f = 0; f < mod->function_count; ++f) {
        const OirFunction* fn = &mod->functions[f];
        fprintf(out, "  /** Bounds: -> [%" PRId64 ", %" PRId64 "] */\n", fn->postcondition.lo, fn->postcondition.hi);
        fprintf(out, "  %s(", fn->name);
        for (size_t p = 0; p < fn->param_count; ++p) {
            fprintf(out, "%s: bigint", fn->params[p].name);
            if (p + 1 < fn->param_count) fprintf(out, ", ");
        }
        fprintf(out, "): bigint;\n");
    }
    fprintf(out, "}\n\n");

    fprintf(out, "export async function load%s(wasmBytes: BufferSource): Promise<%sExports> {\n", module_name, module_name);
    fprintf(out, "  const { instance } = await WebAssembly.instantiate(wasmBytes, {});\n");
    fprintf(out, "  return instance.exports as unknown as %sExports;\n", module_name);
    fprintf(out, "}\n");
}