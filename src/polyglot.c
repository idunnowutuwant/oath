#include "oath/polyglot.h"
#include <string.h>

static const char* rust_cond_op_str(OathCondOp op) {
    switch (op) {
        case COND_EQ: return "==";
        case COND_NE: return "!=";
        case COND_LT: return "<";
        case COND_LE: return "<=";
        case COND_GT: return ">";
        case COND_GE: return ">=";
    }
    return "==";
}

static const char* wasm_cond_op_str(OathCondOp op) {
    switch (op) {
        case COND_EQ: return "i64.eq";
        case COND_NE: return "i64.ne";
        case COND_LT: return "i64.lt_s";
        case COND_LE: return "i64.le_s";
        case COND_GT: return "i64.gt_s";
        case COND_GE: return "i64.ge_s";
    }
    return "i64.eq";
}

